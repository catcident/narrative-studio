async function scrapeNamu(browser, item) {
  const page = await browser.newPage();
  try {
    console.log(`Scraping from Namu: ${item.name}`);
    await page.goto(item.url, { waitUntil: 'domcontentloaded', timeout: 30000 });

    // 전문 인용 섹션 찾기
    const content = await page.evaluate(() => {
      // 전문 인용이 있는 경우
      const fullText = document.querySelector('.wiki-quote-block');
      if (fullText) return fullText.innerText;

      // 일반 본문
      const paragraphs = document.querySelectorAll('.wiki-paragraph');
      let text = '';
      paragraphs.forEach(p => {
        text += p.innerText + '\n\n';
      });
      return text;
    });

    if (content && content.length > 1000) {
      const filePath = path.join(txtDir, `${item.name}.txt`);
      fs.writeFileSync(filePath, content, 'utf8');
      console.log(`  Saved: ${item.name} (${content.length} chars)`);
      return true;
    }
    return false;
  } catch (err) {
    console.log(`  Error: ${item.name} - ${err.message}`);
    return false;
  } finally {
    await page.close();
  }
}

