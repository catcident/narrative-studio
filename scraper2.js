async function main() {
  // 직접 작성 텍스트 저장
  console.log('=== 직접 작성 텍스트 저장 ===');
  for (const [name, content] of Object.entries(directTexts)) {
    const filePath = path.join(txtDir, `${name}.txt`);
    if (!fs.existsSync(filePath)) {
      fs.writeFileSync(filePath, content, 'utf8');
      console.log(`Saved: ${name} (${content.length} chars)`);
    } else {
      console.log(`Skipped (exists): ${name}`);
    }
  }

  // 결과 확인
  const files = fs.readdirSync(txtDir);
  console.log(`\n=== 현재 총 ${files.length}개 파일 ===`);
  files.forEach(f => console.log(`  - ${f}`));
}

main().catch(console.error);
